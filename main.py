# ================= MEMORY =================
def remember(q,a):
    c.execute("INSERT INTO memory VALUES (?,?)",(q.lower(),a))
    conn.commit()

def recall(q):
    c.execute("SELECT a FROM memory WHERE q LIKE?",('%'+q.lower()+'%',))
    d = c.fetchall()
    return random.choice(d)[0] if d else None

