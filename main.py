@app.on_message(filters.me & filters.command("purge","."))
async def purge(_,m):
    if m.reply_to_message:
        try:
            await app.delete_messages(m.chat.id, range(m.reply_to_message.id, m.id+1))
            await m.edit("🗑 Purged")
        except: await m.edit("Can't delete")

